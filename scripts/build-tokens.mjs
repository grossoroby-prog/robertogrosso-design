// Compiles tokens/tokens.json → src/styles/tokens.css (CSS custom properties)
// and src/data/token-stats.json (counts shown on the site).
import { writeFileSync } from 'node:fs';
import { loadTokens, flatten, cssVar } from './tokens-lib.mjs';

const flat = flatten(loadTokens());
const REF = /^\{([^}]+)\}$/;

const lines = Object.entries(flat).map(([name, { value }]) => {
  const m = typeof value === 'string' && value.match(REF);
  const css = m ? `var(${cssVar(m[1])})` : value;
  return `  ${cssVar(name)}: ${css};`;
});

const css = `/* Generated by scripts/build-tokens.mjs from tokens/tokens.json — do not edit by hand. */\n:root {\n${lines.join('\n')}\n}\n`;
writeFileSync(new URL('../src/styles/tokens.css', import.meta.url), css);

const byType = {};
for (const { type } of Object.values(flat)) byType[type] = (byType[type] ?? 0) + 1;
const aliases = Object.values(flat).filter((t) => typeof t.value === 'string' && REF.test(t.value)).length;
writeFileSync(
  new URL('../src/data/token-stats.json', import.meta.url),
  JSON.stringify({ total: Object.keys(flat).length, aliases, byType }, null, 2) + '\n',
);

console.log(`tokens: wrote ${Object.keys(flat).length} variables (${aliases} aliases)`);
